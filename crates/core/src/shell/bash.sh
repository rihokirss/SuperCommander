__sc_initial=1
__sc_prompt() {
    local __sc_status=$?
    if [[ $__sc_initial == 1 ]]; then __sc_initial=0; return "$__sc_status"; fi
    printf '\033]633;SC:__SC_MARKER__:%s\007' "$(printf %s "$PWD" | base64 | tr -d '\n')"
    return "$__sc_status"
}
__sc_change() {
    local __sc_data=$READLINE_LINE __sc_path
    [[ $__sc_data == SC__SC_MARKER__:* ]] || return
    __sc_data=${__sc_data#SC__SC_MARKER__:}
    [[ $__sc_data =~ ^[A-Za-z0-9+/]+={0,2}$ ]] || return
    __sc_path=$(printf %s "$__sc_data" | base64 -d) || return
    READLINE_LINE= READLINE_POINT=0
    if builtin cd -- "$__sc_path"; then
        printf '\033]633;SC:__SC_MARKER__:OK\007'
    else
        printf '\033]633;SC:__SC_MARKER__:FAIL\007'
    fi
}
bind -m emacs-standard -x '"\e[634;__SC_MARKER__~":__sc_change'
bind -m vi-insertion -x '"\e[634;__SC_MARKER__~":__sc_change'
bind -m emacs-standard '"\e[633;__SC_MARKER__~":"\e[634;__SC_MARKER__~\C-m"'
bind -m vi-insertion '"\e[633;__SC_MARKER__~":"\e[634;__SC_MARKER__~\C-m"'
if [[ $(declare -p PROMPT_COMMAND 2>/dev/null) == "declare -a"* ]]; then
    PROMPT_COMMAND+=(__sc_prompt)
else
    PROMPT_COMMAND="${PROMPT_COMMAND:+$PROMPT_COMMAND; }__sc_prompt"
fi
# Only this generated initialization line is removed, never a user command.
if [[ $(HISTTIMEFORMAT= builtin history 1) == *'#SC_INIT___SC_MARKER__' ]]; then
    builtin history -d -1
fi
# Filter only identifiable commands generated by older SuperCommander versions
# from this session's recall list. Do not rewrite a shared history file.
__sc_clean_history() {
    local -a __sc_lines
    local __sc_i __sc_entry __sc_number
    mapfile -t __sc_lines < <(HISTTIMEFORMAT= builtin history)
    for ((__sc_i=${#__sc_lines[@]}-1; __sc_i>=0; __sc_i--)); do
        [[ ${__sc_lines[__sc_i]} =~ ^[[:space:]]*([0-9]+)[[:space:]]+(.*)$ ]] || continue
        __sc_number=${BASH_REMATCH[1]} __sc_entry=${BASH_REMATCH[2]}
        [[ $__sc_entry =~ SC:[[:xdigit:]]{32}: ]] || continue
        if [[ $__sc_entry == "cd -- '"* && $__sc_entry == *" && printf '\033]633;SC:"* && $__sc_entry == *":OK\007'" ]] ||
           [[ $__sc_entry == '__sc_prompt() { local __sc_status=$?;'* && $__sc_entry == *'PROMPT_COMMAND='* ]]; then
            builtin history -d "$__sc_number"
        fi
    done
}
__sc_clean_history
unset -f __sc_clean_history
